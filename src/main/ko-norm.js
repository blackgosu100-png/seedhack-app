// 1688 한국어판(KR-한국어) 화면 글자 → 앱 규칙이 기대하는 중국어 표기로 바꾼다 (순수 로직, Node로 테스트 가능)
// 1688은 언어를 한국어로 두면 카드·상품 페이지 글자를 기계 번역해서 보여 준다("재구매율 71%", "1만+ 구매", "2년만에 정착").
// 판매량·재구매율·최소주문·크기·무게 규칙은 중국어 기준이라, 읽기 전에 한국어 표현을 중국어 표기로 바꿔 같은 규칙을 그대로 쓴다.
// 중국어 화면 글자는 아래 규칙에 걸리지 않아 그대로 지나간다.

// 카드(검색 결과) — 순서 중요: 재구매율·최소주문을 먼저 바꿔야 "구매"가 판매량으로 잘못 읽히지 않는다
const CARD_RULES = [
  [/(?:판매자\s*|상점\s*|상품\s*|매장\s*)?재\s*구매\s*율?\s*[:：]?\s*(\d{1,3}(?:\.\d+)?)\s*%/g, "回头率$1%"],
  [/(\d+)\s*(?:개|세트|pcs|건|쌍|벌)\s*(?:부터|이상)(?:\s*(?:구매|주문|도매|판매|구입))?/gi, "$1件起批"],
  [/최소\s*(?:주문|구매)?\s*(?:수량)?\s*[:：]?\s*(\d+)\s*(?:개|세트|pcs)?(?![\d件])/gi, "$1件起批"],
  // 판매량: "1만+ 구매" / "900+ 구매" / "판매 1.4만개" — 가격(¥0.9) 숫자는 판매량으로 읽지 않는다
  [/(?<![¥￥]\s?)(?<![.\d])(\d+(?:\.\d+)?)\s*만\s*\+?\s*(?:개|건|세트)?\s*(?:구매|판매|거래|구입)/g, "$1万+件"],
  [/(?<![¥￥]\s?)(?<![.\d])(\d+(?:\.\d+)?)\s*\+?\s*(?:개|건|세트)?\s*(?:구매|판매|거래|구입)(?:됨|완료)?/g, "$1+件"],
  [/(?:판매|거래|구매)\s*량?\s*[:：]?\s*(\d+(?:\.\d+)?)\s*(만)?\s*\+?\s*(?:개|건)?(?![\d.]|\s*(?:件|起批|%))/g, (_m, n, man) => `${n}${man ? "万" : ""}+件`],
  [/입점\s*(\d+)\s*년/g, "入驻$1年"],
  [/(\d+)\s*년\s*(?:만에\s*)?(?:정착|입점|차|거주|운영|경력)/g, "入驻$1年"],
  [/(?:운송비|운임|배송비|택배비)\s*[:：]?\s*[¥￥]?\s*(\d+(?:\.\d+)?)\s*(?:위안|元)?/g, "运费$1元"],
  [/무료\s*(?:배송|운송)|(?:배송비|운송비|택배비)\s*무료/g, "包邮"],
  [/(\d+)\s*일\s*(?:이내\s*|안에\s*)?(?:도착|배달|배송)/g, "$1天达"],
  [/모레\s*도착/g, "后天达"], [/(?:내일|익일|다음\s*날)\s*도착/g, "次日达"], [/오늘\s*도착/g, "今天达"],
  [/(?:랭킹|순위|베스트)[^\n\d]{0,12}(\d+)\s*위/g, "榜第$1名"],
  [/동일\s*(?:상품|제품|스타일)[^\n\d]{0,10}(\d+(?:\.\d+)?)/g, "比同款低$1"],
  [/7\s*일[^\n]{0,14}반품/g, "7天无理由"],
  [/(?:1\s*개|한\s*개|단품)\s*(?:위탁\s*배송|대리\s*발송|드롭\s*쉬핑|직송)/g, "一件代发"],
  [/실력\s*(?:상인|상가|판매자)|파워\s*(?:상인|셀러)|인증\s*공장|공장\s*직(?:영|판|송)|엄선/g, "实力"],
];
export function normKoCard(text) {
  let s = String(text || "");
  if (!/[가-힣]/.test(s)) return s;
  for (const [re, to] of CARD_RULES) s = s.replace(re, to);
  return s;
}

// 상품 페이지 크기·무게·박스 수량 라벨 — 긴 표현부터
const SPEC_RULES = [
  [/포장\s*(?:크기|사이즈|치수|규격)/g, "包装尺寸"],
  [/외부\s*상자\s*(?:크기|사이즈|치수)|아웃\s*박스\s*(?:크기|사이즈)/g, "外箱尺寸"],
  [/(?:전체\s*)?상자\s*(?:규격|사양)/g, "整箱规格"],
  [/제품\s*(?:크기|사이즈|치수)/g, "产品尺寸"],
  [/상품\s*(?:크기|사이즈|치수)/g, "商品尺寸"],
  [/(?:단품|개당|단일|1개)\s*(?:무게|중량)/g, "单个重量"],
  [/제품\s*(?:무게|중량)/g, "产品重量"],
  [/상품\s*(?:무게|중량)/g, "商品重量"],
  [/순\s*중량/g, "净重"],
  [/(?:상자|박스)\s*총\s*중량|총\s*중량/g, "毛重"],
  [/(?:박스|상자|카톤)\s*(?:당\s*)?(?:포장\s*)?(?:수량|개수|입수)|포장\s*수량/g, "装箱数量"],
  [/(?:크기|사이즈|치수)/g, "尺寸"],
  [/(?:무게|중량)/g, "重量"],
  [/센티미터|센티/g, "cm"], [/밀리미터|밀리/g, "mm"], [/킬로그램|킬로/g, "kg"], [/(\d)\s*그램/g, "$1g"],
];
export function normKoSpecs(text) {
  let s = String(text || "");
  if (!/[가-힣]/.test(s)) return s;
  for (const [re, to] of SPEC_RULES) s = s.replace(re, to);
  return s;
}

